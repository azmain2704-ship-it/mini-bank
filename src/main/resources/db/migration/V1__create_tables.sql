-- Money is stored as whole pence in BIGINT columns. The CHECK constraints repeat the app's rules in the database,
-- so even a bug in the Java code can't leave an account negative or record a zero/negative transfer.

CREATE TABLE accounts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_name    VARCHAR(100) NOT NULL,
    balance_pence BIGINT       NOT NULL CHECK (balance_pence >= 0),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE transfers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_account_id  BIGINT       NOT NULL REFERENCES accounts (id),
    to_account_id    BIGINT       NOT NULL REFERENCES accounts (id),
    amount_pence     BIGINT       NOT NULL CHECK (amount_pence > 0),
    status           VARCHAR(20)  NOT NULL CHECK (status IN ('COMPLETED', 'REJECTED')),
    rejection_reason VARCHAR(200),
    idempotency_key  VARCHAR(100) UNIQUE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (from_account_id <> to_account_id)
);

CREATE INDEX idx_transfers_from_created ON transfers (from_account_id, created_at);
CREATE INDEX idx_transfers_to_created ON transfers (to_account_id, created_at);

CREATE TABLE fraud_flags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT       NOT NULL REFERENCES transfers (id),
    reason      VARCHAR(30)  NOT NULL,
    detail      VARCHAR(300) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_fraud_flags_transfer ON fraud_flags (transfer_id);
